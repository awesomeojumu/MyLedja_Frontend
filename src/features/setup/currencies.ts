const byCode = new Map(CURRENCIES.map((c) => [c.code, c]));

export function currencyLabel(code: string): string {
  const hit = byCode.get(code);
  return hit ? `${hit.name} (${hit.code})` : code;
}

/** Append a code the person chose. Unknown codes and duplicates stay out. */
export function addPreferredCurrency(list: readonly string[], code: string): string[] {
  const next = code.trim().toUpperCase();
  if (!byCode.has(next) || list.includes(next)) return [...list];
  return [...list, next];
}

export function filterCurrencies(query: string): Currency[] {
  const q = query.trim().toLowerCase();
  const matched = q
    ? CURRENCIES.filter((c) => c.name.toLowerCase().includes(q) || c.code.toLowerCase().includes(q))
    : CURRENCIES;
  return [...matched].sort((a, b) => {
    if (!q && a.code === 'NGN') return -1;
    if (!q && b.code === 'NGN') return 1;
    return a.name.localeCompare(b.name);
  });
}
