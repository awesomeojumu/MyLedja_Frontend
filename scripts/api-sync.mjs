// npm run api:sync  copies ../MyLedja_Backend/openapi.json and regenerates src/api/types.ts.
// npm run api:check fails if src/api/types.ts wasn't generated from the committed src/api/openapi.json.
import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { copyFileSync, existsSync, readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const root = resolve(import.meta.dirname, '..');
const spec = resolve(root, 'src/api/openapi.json');
const types = resolve(root, 'src/api/types.ts');
const backendSpec = resolve(root, '../MyLedja_Backend/openapi.json');
const check = process.argv.includes('--check');

const hashOf = (file) => createHash('sha256').update(readFileSync(file)).digest('hex');
const header = (hash) => `// Generated by npm run api:sync from openapi.json sha256:${hash}. Don't edit.\n`;

if (check) {
  if (!existsSync(spec)) {
    console.log('api:check: no openapi.json committed yet; nothing to compare.');
    process.exit(0);
  }
  const firstLine = existsSync(types) ? readFileSync(types, 'utf8').split('\n')[0] + '\n' : '';
  if (firstLine !== header(hashOf(spec))) {
    console.error('api:check: src/api/types.ts does not match src/api/openapi.json. Run npm run api:sync.');
    process.exit(1);
  }
  console.log('api:check: types match openapi.json.');
  process.exit(0);
}

if (!existsSync(backendSpec)) {
  console.error('api:sync: ../MyLedja_Backend/openapi.json not found.');
  process.exit(1);
}
copyFileSync(backendSpec, spec);
const body = execFileSync('npx', ['--yes', 'openapi-typescript@7.13.0', spec], { encoding: 'utf8' });
writeFileSync(types, header(hashOf(spec)) + body);
console.log('api:sync: wrote src/api/types.ts');
