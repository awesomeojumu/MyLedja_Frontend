// npm run api:sync [-- --from <path>]  copies the backend's openapi.json and regenerates src/api/types.ts.
// Default source: ../MyLedja_Backend/openapi.json, then ../myledja_backend/openapi.json.
// npm run api:check regenerates types from the committed src/api/openapi.json and fails if they differ.
import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { copyFileSync, existsSync, readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const root = resolve(import.meta.dirname, '..');
const spec = resolve(root, 'src/api/openapi.json');
const types = resolve(root, 'src/api/types.ts');
const fromIndex = process.argv.indexOf('--from');
const check = process.argv.includes('--check');

const defaultCandidates = [
  resolve(root, '../MyLedja_Backend/openapi.json'),
  resolve(root, '../myledja_backend/openapi.json'),
];

const hashOf = (file) => createHash('sha256').update(readFileSync(file)).digest('hex');
const header = (hash) => `// Generated by npm run api:sync from openapi.json sha256:${hash}. Don't edit.\n`;

function generateTypes(specPath) {
  const body = execFileSync('npx', ['--yes', 'openapi-typescript@7.13.0', specPath], { encoding: 'utf8' });
  return header(hashOf(specPath)) + body;
}

if (check) {
  if (!existsSync(spec)) {
    console.error('api:check: src/api/openapi.json is missing. Run npm run api:sync.');
    process.exit(1);
  }
  const expected = generateTypes(spec);
  const committed = existsSync(types) ? readFileSync(types, 'utf8') : '';
  if (committed !== expected) {
    console.error('api:check: src/api/types.ts does not match src/api/openapi.json. Run npm run api:sync.');
    process.exit(1);
  }
  console.log('api:check: types match openapi.json.');
  process.exit(0);
}

const backendSpec =
  fromIndex > -1
    ? resolve(process.argv[fromIndex + 1])
    : defaultCandidates.find((p) => existsSync(p));

if (!backendSpec || !existsSync(backendSpec)) {
  console.error(
    `api:sync: backend openapi.json not found. Tried: ${fromIndex > -1 ? resolve(process.argv[fromIndex + 1]) : defaultCandidates.join(', ')}`,
  );
  process.exit(1);
}

copyFileSync(backendSpec, spec);
writeFileSync(types, generateTypes(spec));
console.log(`api:sync: copied ${backendSpec} → src/api/openapi.json and wrote src/api/types.ts`);
